//go:build ignore

// Generates a Go build overlay; product source files are never rewritten.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
)

func main() {
	output := flag.String("output", "build/server-writer/overlay", "generated overlay directory")
	model := flag.String("model", "writer", "socket model: baseline, writer or batch")
	slots := flag.Int("slots", 0, "experimental queue capacity and counters: 4 or 16; 0 leaves queues unchanged")
	flag.Parse()
	if err := prepare(*output, *model, *slots); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func prepare(output, model string, slots int) error {
	if model != "baseline" && model != "writer" && model != "batch" {
		return fmt.Errorf("model must be baseline, writer or batch")
	}
	if slots != 0 && slots != 4 && slots != 16 {
		return fmt.Errorf("slots must be 0, 4 or 16")
	}
	root, err := filepath.Abs(".")
	if err != nil {
		return err
	}
	output, err = filepath.Abs(output)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(output, 0o755); err != nil {
		return err
	}
	replace := make(map[string]string)
	if model != "baseline" {
		if err := prepareWriter(root, output, replace); err != nil {
			return err
		}
		if model == "batch" {
			experiment := filepath.Join(root, "test/server-perf/socketwriter")
			replace[filepath.Join(root, "internal/noiseudp/writer_experiment.go")] = filepath.Join(experiment, "batch.go.txt")
			replace[filepath.Join(root, "internal/noiseudp/batch_experiment_test.go")] = filepath.Join(experiment, "batch_test.go.txt")
			replace[filepath.Join(root, "internal/server/batch_experiment_test.go")] = filepath.Join(experiment, "batch_probe.go.txt")
		}
	}
	if slots != 0 {
		if err := prepareQueue(root, output, slots, replace); err != nil {
			return err
		}
	}
	overlay, err := json.MarshalIndent(map[string]any{"Replace": replace}, "", "  ")
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(output, "overlay.json"), overlay, 0o644)
}

func prepareWriter(root, output string, replace map[string]string) error {
	fset := token.NewFileSet()
	source := filepath.Join(root, "internal/noiseudp/handshake.go")
	f, err := parser.ParseFile(fset, source, nil, parser.ParseComments)
	if err != nil {
		return err
	}
	selector := func(field string) *ast.SelectorExpr {
		return &ast.SelectorExpr{X: ast.NewIdent("l"), Sel: ast.NewIdent(field)}
	}
	changed := 0
	for _, decl := range f.Decls {
		switch d := decl.(type) {
		case *ast.GenDecl:
			for _, spec := range d.Specs {
				if t, ok := spec.(*ast.TypeSpec); ok && t.Name.Name == "Listener" {
					s := t.Type.(*ast.StructType)
					s.Fields.List = append(s.Fields.List, &ast.Field{Names: []*ast.Ident{ast.NewIdent("experimentWriter")}, Type: &ast.StarExpr{X: ast.NewIdent("soloWriter")}})
					changed++
				}
			}
		case *ast.FuncDecl:
			switch d.Name.Name {
			case "Listen":
				for i, s := range d.Body.List {
					g, ok := s.(*ast.GoStmt)
					if !ok {
						continue
					}
					call, ok := g.Call.Fun.(*ast.SelectorExpr)
					if ok && call.Sel.Name == "loop" {
						added := &ast.ExprStmt{X: &ast.CallExpr{Fun: selector("startWriterExperiment")}}
						d.Body.List = append(d.Body.List[:i], append([]ast.Stmt{added}, d.Body.List[i:]...)...)
						changed++
						break
					}
				}
			case "Close":
				wait := &ast.IfStmt{Cond: &ast.BinaryExpr{X: selector("experimentWriter"), Op: token.NEQ, Y: ast.NewIdent("nil")}, Body: &ast.BlockStmt{List: []ast.Stmt{
					&ast.ExprStmt{X: &ast.UnaryExpr{Op: token.ARROW, X: &ast.SelectorExpr{X: selector("experimentWriter"), Sel: ast.NewIdent("done")}}},
				}}}
				i := len(d.Body.List) - 1
				d.Body.List = append(d.Body.List[:i], wait, d.Body.List[i])
				changed++
			case "write":
				d.Name.Name = "writeDirect"
				changed++
			}
		}
	}
	if changed != 4 {
		return fmt.Errorf("listener source changed: expected 4 overlay edits, got %d", changed)
	}
	var generated bytes.Buffer
	if err := format.Node(&generated, fset, f); err != nil {
		return err
	}
	modified := filepath.Join(output, "handshake.go.txt")
	if err := os.WriteFile(modified, generated.Bytes(), 0o644); err != nil {
		return err
	}
	experiment := filepath.Join(root, "test/server-perf/socketwriter")
	replace[source] = modified
	replace[filepath.Join(root, "internal/noiseudp/writer_common_experiment.go")] = filepath.Join(experiment, "writer_common.go.txt")
	replace[filepath.Join(root, "internal/noiseudp/writer_experiment.go")] = filepath.Join(experiment, "writer.go.txt")
	replace[filepath.Join(root, "internal/noiseudp/writer_experiment_test.go")] = filepath.Join(experiment, "writer_test.go.txt")
	return nil
}

func prepareQueue(root, output string, slots int, replace map[string]string) error {
	for _, name := range []string{"internal/server/server.go", "internal/nativewire/voice_ring.go", "internal/nativewire/transport.go", "internal/noiseudp/conn.go"} {
		fset := token.NewFileSet()
		source := filepath.Join(root, name)
		f, err := parser.ParseFile(fset, source, nil, parser.ParseComments)
		if err != nil {
			return err
		}
		changed := 0
		switch name {
		case "internal/noiseudp/conn.go":
			ast.Inspect(f, func(n ast.Node) bool {
				branch, ok := n.(*ast.CaseClause)
				if !ok || len(branch.List) != 1 {
					return true
				}
				kind, ok := branch.List[0].(*ast.Ident)
				if !ok || kind.Name != "voice" {
					return true
				}
				ast.Inspect(branch, func(child ast.Node) bool {
					clause, ok := child.(*ast.CommClause)
					if ok && clause.Comm == nil {
						counter, err := parser.ParseExpr("experimentReceiveDrops.Add(1)")
						if err != nil {
							panic(err)
						}
						clause.Body = append(clause.Body, &ast.ExprStmt{X: counter})
						changed++
					}
					return true
				})
				return false
			})
		case "internal/server/server.go":
			ast.Inspect(f, func(n ast.Node) bool {
				call, ok := n.(*ast.CallExpr)
				if !ok {
					return true
				}
				fun, ok := call.Fun.(*ast.SelectorExpr)
				if ok && fun.Sel.Name == "NewVoiceRing" && len(call.Args) == 1 {
					call.Args[0] = &ast.BasicLit{Kind: token.INT, Value: fmt.Sprint(slots)}
					changed++
				}
				return true
			})
		case "internal/nativewire/voice_ring.go":
			ast.Inspect(f, func(n ast.Node) bool {
				switch d := n.(type) {
				case *ast.TypeSpec:
					if d.Name.Name == "VoiceRing" {
						s := d.Type.(*ast.StructType)
						s.Fields.List = append(s.Fields.List, &ast.Field{Names: []*ast.Ident{ast.NewIdent("experimentEnqueued"), ast.NewIdent("experimentOverwritten")}, Type: ast.NewIdent("uint64")})
						changed++
					}
				case *ast.FuncDecl:
					if d.Name.Name != "Push" {
						break
					}
					for i, stmt := range d.Body.List {
						branch, ok := stmt.(*ast.IfStmt)
						if !ok {
							continue
						}
						cond, ok := branch.Cond.(*ast.BinaryExpr)
						if !ok || cond.Op != token.EQL {
							continue
						}
						field, ok := cond.X.(*ast.SelectorExpr)
						if ok && field.Sel.Name == "size" {
							increment := func(name string) ast.Stmt {
								return &ast.IncDecStmt{X: &ast.SelectorExpr{X: ast.NewIdent("q"), Sel: ast.NewIdent(name)}, Tok: token.INC}
							}
							branch.Body.List = append([]ast.Stmt{increment("experimentOverwritten")}, branch.Body.List...)
							d.Body.List = append(d.Body.List[:i], append([]ast.Stmt{increment("experimentEnqueued")}, d.Body.List[i:]...)...)
							changed++
							break
						}
					}
				}
				return true
			})
		case "internal/nativewire/transport.go":
			ast.Inspect(f, func(n ast.Node) bool {
				branch, ok := n.(*ast.IfStmt)
				if !ok {
					return true
				}
				cond, ok := branch.Cond.(*ast.BinaryExpr)
				if !ok || cond.Op != token.GTR {
					return true
				}
				call, ok := cond.X.(*ast.CallExpr)
				if !ok {
					return true
				}
				fun, ok := call.Fun.(*ast.SelectorExpr)
				if ok && fun.Sel.Name == "Since" {
					counter, err := parser.ParseExpr("experimentExpired.Add(1)")
					if err != nil {
						panic(err)
					}
					branch.Body.List = append([]ast.Stmt{&ast.ExprStmt{X: counter}}, branch.Body.List...)
					changed++
				}
				return true
			})
		}
		want := 1
		if name == "internal/nativewire/voice_ring.go" {
			want = 2
		}
		if changed != want {
			return fmt.Errorf("%s changed: expected %d queue overlay edits, got %d", name, want, changed)
		}
		var generated bytes.Buffer
		if err := format.Node(&generated, fset, f); err != nil {
			return err
		}
		modified := filepath.Join(output, filepath.Base(name)+".txt")
		if err := os.WriteFile(modified, generated.Bytes(), 0o644); err != nil {
			return err
		}
		replace[source] = modified
	}
	experiment := filepath.Join(root, "test/server-perf/socketwriter")
	for target, fixture := range map[string]string{
		"internal/noiseudp/receive_experiment.go":      "receive.go.txt",
		"internal/server/receive_experiment_test.go":   "receive_probe.go.txt",
		"internal/nativewire/queue_experiment.go":      "queue.go.txt",
		"internal/nativewire/queue_experiment_test.go": "queue_test.go.txt",
		"internal/server/queue_experiment_test.go":     "queue_probe.go.txt",
		"internal/server/queue_snapshot_test.go":       "queue_probe_test.go.txt",
	} {
		replace[filepath.Join(root, target)] = filepath.Join(experiment, fixture)
	}
	return nil
}
